USE ROLE SYSADMIN;
USE WAREHOUSE BLOG_AIF_WH;
USE SCHEMA BLOG_AIF_TEST.T;
CREATE OR REPLACE TABLE tickets_masked AS SELECT * FROM tickets;
CREATE OR REPLACE MASKING POLICY mp_redact AS (v STRING) RETURNS STRING ->
  CASE WHEN CURRENT_ROLE() = 'ACCOUNTADMIN' THEN v ELSE AI_REDACT(v) END;
ALTER TABLE tickets_masked MODIFY COLUMN body SET MASKING POLICY mp_redact;
SELECT id, body FROM tickets_masked WHERE id IN (4, 5) ORDER BY id;
