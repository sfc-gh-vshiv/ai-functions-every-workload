USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BLOG_AIF_WH;
USE SCHEMA BLOG_AIF_TEST.T;
CREATE OR REPLACE TABLE alert_log (fired_at TIMESTAMP_LTZ);
CREATE OR REPLACE ALERT a_safety
  WAREHOUSE = BLOG_AIF_WH
  SCHEDULE = '60 MINUTE'
  IF (EXISTS (
    SELECT 1 FROM tickets
    WHERE AI_FILTER(PROMPT('Does this describe a safety hazard to a person? {0}', body))))
  THEN INSERT INTO alert_log SELECT CURRENT_TIMESTAMP();
EXECUTE ALERT a_safety;
