USE ROLE SYSADMIN;
USE WAREHOUSE BLOG_AIF_WH;
USE SCHEMA BLOG_AIF_TEST.T;
CREATE OR REPLACE DATA METRIC FUNCTION dmf_complaints(t TABLE(body STRING))
  RETURNS NUMBER
  AS 'SELECT COUNT_IF(AI_FILTER(PROMPT(''Is this a customer complaint? {0}'', body))) FROM t';
SELECT dmf_complaints(SELECT body FROM tickets) AS complaints;
ALTER TABLE tickets SET DATA_METRIC_SCHEDULE = '60 MINUTE';
ALTER TABLE tickets ADD DATA METRIC FUNCTION dmf_complaints ON (body);
