USE ROLE SYSADMIN;
USE WAREHOUSE BLOG_AIF_WH;
USE SCHEMA BLOG_AIF_TEST.T;
CREATE OR REPLACE STAGE stg FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"');
COPY INTO @stg/t.csv FROM (SELECT id, body FROM tickets)
  FILE_FORMAT = (TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"')
  SINGLE = TRUE OVERWRITE = TRUE;
CREATE OR REPLACE TABLE tickets_loaded (id INT, body STRING, topic STRING);
COPY INTO tickets_loaded FROM (
  SELECT $1, $2, AI_CLASSIFY($2, ['billing', 'delivery', 'safety', 'other']):labels[0]::STRING
  FROM @stg/t.csv);
