-- 00_setup.sql: role, warehouse, database, stages and the results table.
-- Run once as a user who can use ACCOUNTADMIN (it creates roles and grants).
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS AIFW_ROLE;
GRANT ROLE AIFW_ROLE TO ROLE SYSADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AIFW_ROLE;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE AIFW_ROLE;  -- PUBLIC has it by default; an admin may have revoked it
GRANT CREATE DATABASE, CREATE WAREHOUSE ON ACCOUNT TO ROLE AIFW_ROLE;
GRANT EXECUTE TASK, EXECUTE ALERT ON ACCOUNT TO ROLE AIFW_ROLE;
GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE AIFW_ROLE;  -- w04 attaches a masking policy
-- The masking policy in w04 shows raw notes only to this role. Grant it to no one for the demo.
CREATE ROLE IF NOT EXISTS AIFW_PII_READER;
SET CURRENT_USER_NAME = CURRENT_USER();
GRANT ROLE AIFW_ROLE TO USER IDENTIFIER($CURRENT_USER_NAME);

USE ROLE AIFW_ROLE;
-- Docs recommend a warehouse no larger than MEDIUM for AI Functions. XS is enough here.
CREATE WAREHOUSE IF NOT EXISTS AIFW_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS AIFW;
CREATE SCHEMA IF NOT EXISTS AIFW.W;
USE SCHEMA AIFW.W;

-- AI_EXTRACT and AI_TRANSCRIBE read files through TO_FILE: server-side encryption plus a directory table.
CREATE STAGE IF NOT EXISTS INVOICES ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') DIRECTORY = (ENABLE = TRUE);
CREATE STAGE IF NOT EXISTS CALLS    ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') DIRECTORY = (ENABLE = TRUE);
CREATE STAGE IF NOT EXISTS RAW_CSV  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');

CREATE TABLE IF NOT EXISTS RESULTS (
  RUN STRING, WORKLOAD STRING, METRIC STRING, VALUE FLOAT, NOTE STRING,
  RECORDED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
-- w02 writes its refresh query IDs here; sql/meter.sql and tools/export_results.py read it,
-- so it exists even when you run only some workloads.
CREATE TABLE IF NOT EXISTS W02_REFRESHES (RUN STRING, QUERY_ID STRING, REFRESH_ACTION STRING, REFRESH_TRIGGER STRING,
  INSERTED_ROWS INT, REFRESH_START_TIME TIMESTAMP_LTZ, REFRESH_END_TIME TIMESTAMP_LTZ);
