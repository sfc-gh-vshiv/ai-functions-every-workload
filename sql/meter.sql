-- meter.sql: what each workload actually cost, from the billing views.
-- AI Credits come from ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY, which lags behind real time.
-- Run this again later if rows are missing (see pending_queries in the output).
-- w02 refreshes are matched to W02_REFRESHES by QUERY_ID, so each refresh shows its own cost.
-- Vars: run
USE ROLE ACCOUNTADMIN; USE WAREHOUSE AIFW_WH; USE SCHEMA AIFW.W;

CREATE OR REPLACE TEMPORARY TABLE METER_ROWS AS
SELECT IFF(r.QUERY_ID IS NOT NULL, 'w02:refresh_' || LOWER(r.REFRESH_ACTION) || '_' || LOWER(r.REFRESH_TRIGGER),
           SPLIT_PART(h.QUERY_TAG, ':', 3) || IFF(SPLIT_PART(h.QUERY_TAG, ':', 4) = '', '', ':' || SPLIT_PART(h.QUERY_TAG, ':', 4))) AS WORKLOAD,
       h.FUNCTION_NAME, h.MODEL_NAME, h.QUERY_ID, h.CREDITS, h.START_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY h
LEFT JOIN AIFW.W.W02_REFRESHES r ON r.QUERY_ID = h.QUERY_ID AND r.RUN = '<% run %>'
WHERE (h.QUERY_TAG LIKE 'aifw:<% run %>:%' OR r.QUERY_ID IS NOT NULL)
  AND h.START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP());

-- Every w02 refresh with its bill. A refresh with no new rows has no billing row: 0 AI Credits.
SELECT r.REFRESH_TRIGGER, r.REFRESH_ACTION, r.INSERTED_ROWS, COALESCE(ROUND(SUM(m.CREDITS), 6), 0) AS AI_CREDITS
FROM AIFW.W.W02_REFRESHES r LEFT JOIN METER_ROWS m ON m.QUERY_ID = r.QUERY_ID
WHERE r.RUN = '<% run %>' GROUP BY 1, 2, 3, r.REFRESH_START_TIME ORDER BY r.REFRESH_START_TIME;

-- One line per workload and function.
SELECT WORKLOAD, FUNCTION_NAME, MODEL_NAME, COUNT(DISTINCT QUERY_ID) AS QUERIES,
       ROUND(SUM(CREDITS), 4) AS AI_CREDITS, ROUND(SUM(CREDITS) * 2.00, 2) AS USD_AT_2_PER_CREDIT
FROM METER_ROWS GROUP BY 1, 2, 3 ORDER BY 1, 2;

-- Queries that ran with this run's tag but have no billing row yet. Wait and rerun if this is not zero.
SELECT COUNT(*) AS PENDING_QUERIES
FROM TABLE(AIFW.INFORMATION_SCHEMA.QUERY_HISTORY_BY_USER(RESULT_LIMIT => 10000)) q
WHERE q.QUERY_TAG LIKE 'aifw:<% run %>:w%' AND q.EXECUTION_STATUS = 'SUCCESS'
  AND q.QUERY_TYPE IN ('CREATE_TABLE_AS_SELECT', 'INSERT')
  AND q.QUERY_TEXT ILIKE '%AI\\_%' ESCAPE '\\'
  AND q.QUERY_TEXT NOT ILIKE 'INSERT INTO RESULTS%' AND q.QUERY_TEXT NOT ILIKE '%DYNAMIC TABLE%'
  AND q.QUERY_ID NOT IN (SELECT QUERY_ID FROM METER_ROWS);

-- Warehouse runtime per workload (warehouse credits are billed separately from AI Credits).
SELECT SPLIT_PART(QUERY_TAG, ':', 3) AS WORKLOAD, COUNT(*) AS QUERIES,
       ROUND(SUM(TOTAL_ELAPSED_TIME) / 1000, 1) AS ELAPSED_SECONDS
FROM TABLE(AIFW.INFORMATION_SCHEMA.QUERY_HISTORY_BY_USER(RESULT_LIMIT => 10000))
WHERE QUERY_TAG LIKE 'aifw:<% run %>:%' GROUP BY 1 ORDER BY 1;

-- Record the totals next to the quality metrics.
DELETE FROM RESULTS WHERE RUN = '<% run %>' AND METRIC IN ('ai_credits', 'elapsed_seconds');
INSERT INTO RESULTS (RUN, WORKLOAD, METRIC, VALUE, NOTE)
SELECT '<% run %>', SPLIT_PART(WORKLOAD, ':', 1), 'ai_credits', SUM(CREDITS), LISTAGG(DISTINCT FUNCTION_NAME, ', ')
FROM METER_ROWS GROUP BY 2
UNION ALL
SELECT '<% run %>', SPLIT_PART(QUERY_TAG, ':', 3), 'elapsed_seconds', SUM(TOTAL_ELAPSED_TIME) / 1000, NULL
FROM TABLE(AIFW.INFORMATION_SCHEMA.QUERY_HISTORY_BY_USER(RESULT_LIMIT => 10000))
WHERE QUERY_TAG LIKE 'aifw:<% run %>:%' GROUP BY 2;

SELECT ROUND(SUM(CREDITS), 4) AS RUN_AI_CREDITS, ROUND(SUM(CREDITS) * 2.00, 2) AS RUN_USD, MAX(START_TIME) AS LATEST_BILLING_ROW
FROM METER_ROWS;
