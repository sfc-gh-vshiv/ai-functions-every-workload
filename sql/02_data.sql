-- 02_data.sql: upload the generated CSVs and load the source tables.
-- Run from the repo root (PUT paths are relative): snow sql -f sql/02_data.sql
USE ROLE AIFW_ROLE;
USE WAREHOUSE AIFW_WH;
USE SCHEMA AIFW.W;

PUT file://data/csv/*.csv.gz @RAW_CSV AUTO_COMPRESS = FALSE OVERWRITE = TRUE;

CREATE OR REPLACE FILE FORMAT CSV_GZ TYPE = CSV COMPRESSION = GZIP SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' ENCODING = 'UTF8';

CREATE OR REPLACE TABLE TICKETS (ID INT, CREATED_AT TIMESTAMP_NTZ, BODY STRING, TRUE_CATEGORY STRING, ALT_CATEGORY STRING);
CREATE OR REPLACE TABLE TICKETS_NEW LIKE TICKETS;
CREATE OR REPLACE TABLE REVIEWS (ID INT, PRODUCT STRING, STARS INT, BODY STRING, TRUE_CONTRADICTION BOOLEAN, COMPLAINT_KEY STRING, TOP_COMPLAINT_KEY STRING);
CREATE OR REPLACE TABLE NOTES (ID INT, NOTE STRING, HAS_PII BOOLEAN, PLANTED_PII STRING);
CREATE OR REPLACE TABLE LOGS (ID INT, TS TIMESTAMP_NTZ, LINE STRING, TRUE_CLASS STRING);
CREATE OR REPLACE TABLE PRODUCTS (ID INT, FAMILY STRING, DESCRIPTION STRING);
CREATE OR REPLACE TABLE FOREIGN_TICKETS (ID INT, LANG STRING, BODY STRING, TRUE_CATEGORY STRING, ORDER_REF STRING);

COPY INTO TICKETS         FROM @RAW_CSV/tickets.csv.gz         FILE_FORMAT = CSV_GZ;
COPY INTO TICKETS_NEW     FROM @RAW_CSV/tickets_new.csv.gz     FILE_FORMAT = CSV_GZ;
COPY INTO REVIEWS         FROM @RAW_CSV/reviews.csv.gz         FILE_FORMAT = CSV_GZ;
COPY INTO NOTES           FROM @RAW_CSV/notes.csv.gz           FILE_FORMAT = CSV_GZ;
COPY INTO LOGS            FROM @RAW_CSV/logs.csv.gz            FILE_FORMAT = CSV_GZ;
COPY INTO PRODUCTS        FROM @RAW_CSV/products.csv.gz        FILE_FORMAT = CSV_GZ;
COPY INTO FOREIGN_TICKETS FROM @RAW_CSV/foreign_tickets.csv.gz FILE_FORMAT = CSV_GZ;

-- Held-out test sets (tools/heldout_phrases.py): new phrasings that no template or prompt was built from.
CREATE OR REPLACE TABLE HELDOUT_TICKETS (ID INT, TRUE_CATEGORY STRING, BODY STRING);
CREATE OR REPLACE TABLE HELDOUT_LOGS (ID INT, TRUE_CLASS STRING, LINE STRING);
CREATE OR REPLACE TABLE HELDOUT_QUERIES (ID INT, FAMILY STRING, Q STRING);
COPY INTO HELDOUT_TICKETS FROM @RAW_CSV/heldout_tickets.csv.gz FILE_FORMAT = CSV_GZ;
COPY INTO HELDOUT_LOGS    FROM @RAW_CSV/heldout_logs.csv.gz    FILE_FORMAT = CSV_GZ;
COPY INTO HELDOUT_QUERIES FROM @RAW_CSV/heldout_queries.csv.gz FILE_FORMAT = CSV_GZ;

-- Files for w01 (invoices) and w08 (calls), plus their truth tables.
PUT file://data/invoices/*.pdf @INVOICES AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
PUT file://data/calls/*.mp3    @CALLS    AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
PUT file://data/invoices/truth.csv @RAW_CSV/invoices/ AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT file://data/calls/truth.csv    @RAW_CSV/calls/    AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
ALTER STAGE INVOICES REFRESH;
ALTER STAGE CALLS REFRESH;

CREATE OR REPLACE TABLE INVOICE_TRUTH (FILE STRING, LAYOUT INT, VENDOR STRING, INVOICE_NO STRING, INVOICE_DATE DATE, TOTAL NUMBER(12,2));
CREATE OR REPLACE TABLE CALL_TRUTH (FILE STRING, OUTCOME STRING, TRUE_SENTIMENT STRING, SCRIPT STRING);
COPY INTO INVOICE_TRUTH FROM @RAW_CSV/invoices/truth.csv.gz FILE_FORMAT = CSV_GZ;
COPY INTO CALL_TRUTH    FROM @RAW_CSV/calls/truth.csv.gz    FILE_FORMAT = CSV_GZ;

SELECT 'TICKETS' t, COUNT(*) n FROM TICKETS UNION ALL SELECT 'TICKETS_NEW', COUNT(*) FROM TICKETS_NEW
UNION ALL SELECT 'REVIEWS', COUNT(*) FROM REVIEWS UNION ALL SELECT 'NOTES', COUNT(*) FROM NOTES
UNION ALL SELECT 'LOGS', COUNT(*) FROM LOGS UNION ALL SELECT 'PRODUCTS', COUNT(*) FROM PRODUCTS
UNION ALL SELECT 'FOREIGN_TICKETS', COUNT(*) FROM FOREIGN_TICKETS
UNION ALL SELECT 'INVOICE_FILES', COUNT(*) FROM DIRECTORY(@INVOICES) UNION ALL SELECT 'CALL_FILES', COUNT(*) FROM DIRECTORY(@CALLS)
UNION ALL SELECT 'INVOICE_TRUTH', COUNT(*) FROM INVOICE_TRUTH UNION ALL SELECT 'CALL_TRUTH', COUNT(*) FROM CALL_TRUTH
UNION ALL SELECT 'HELDOUT_TICKETS', COUNT(*) FROM HELDOUT_TICKETS UNION ALL SELECT 'HELDOUT_LOGS', COUNT(*) FROM HELDOUT_LOGS
UNION ALL SELECT 'HELDOUT_QUERIES', COUNT(*) FROM HELDOUT_QUERIES;
