-- w08 Contact center: AI_TRANSCRIBE turns call audio into text, then AI_SENTIMENT scores each call.
-- Vars: run, n (number of calls)
USE ROLE AIFW_ROLE; USE WAREHOUSE AIFW_WH; USE SCHEMA AIFW.W;
ALTER SESSION SET QUERY_TAG = 'aifw:<% run %>:w08';

CREATE OR REPLACE TABLE W08_CALLS AS
SELECT d.RELATIVE_PATH AS FILE, AI_TRANSCRIBE(TO_FILE('@CALLS', d.RELATIVE_PATH)) AS T
FROM DIRECTORY(@CALLS) d
WHERE d.RELATIVE_PATH ILIKE '%.mp3'
ORDER BY d.RELATIVE_PATH
LIMIT <% n %>;

CREATE OR REPLACE TABLE W08_SCORED AS
WITH s AS (
  SELECT c.FILE, c.T:text::STRING AS TRANSCRIPT, c.T:audio_duration::FLOAT AS SECONDS,
         AI_SENTIMENT(c.T:text::STRING) AS SENT, t.OUTCOME, t.TRUE_SENTIMENT, t.SCRIPT,
         REGEXP_SUBSTR(t.SCRIPT, 'A-([0-9]{6})', 1, 1, 'e') AS ORDER_DIGITS
  FROM W08_CALLS c JOIN CALL_TRUTH t ON t.FILE = c.FILE)
SELECT FILE, OUTCOME, TRUE_SENTIMENT, SECONDS, TRANSCRIPT, SCRIPT,
       SENT:categories[0]:sentiment::STRING AS SENTIMENT,
       -- character-level similarity: 1 - edit distance / length of the longer text, both after normalising case and punctuation
       1 - EDITDISTANCE(REGEXP_REPLACE(LOWER(TRANSCRIPT), '[^a-z0-9 ]', ''), REGEXP_REPLACE(LOWER(SCRIPT), '[^a-z0-9 ]', ''))
           / GREATEST(LENGTH(REGEXP_REPLACE(LOWER(TRANSCRIPT), '[^a-z0-9 ]', '')), LENGTH(REGEXP_REPLACE(LOWER(SCRIPT), '[^a-z0-9 ]', ''))) AS CHAR_SIMILARITY,
       IFF(ORDER_DIGITS IS NULL, NULL, CONTAINS(REGEXP_REPLACE(TRANSCRIPT, '[^0-9]', ''), ORDER_DIGITS)) AS ORDER_NO_CAPTURED
FROM s;

DELETE FROM RESULTS WHERE RUN = '<% run %>' AND WORKLOAD = 'w08';
INSERT INTO RESULTS (RUN, WORKLOAD, METRIC, VALUE, NOTE)
          SELECT '<% run %>', 'w08', 'calls', COUNT(*), NULL FROM W08_SCORED
UNION ALL SELECT '<% run %>', 'w08', 'audio_seconds', SUM(SECONDS), NULL FROM W08_SCORED
UNION ALL SELECT '<% run %>', 'w08', 'avg_char_similarity', AVG(CHAR_SIMILARITY), 'transcript vs script' FROM W08_SCORED
UNION ALL SELECT '<% run %>', 'w08', 'order_no_captured', AVG(IFF(ORDER_NO_CAPTURED, 1, 0)), 'calls that state an order number'
          FROM W08_SCORED WHERE ORDER_NO_CAPTURED IS NOT NULL
UNION ALL SELECT '<% run %>', 'w08', 'sentiment_accuracy', AVG(IFF(SENTIMENT = TRUE_SENTIMENT, 1, 0)), 'positive/negative per script' FROM W08_SCORED
UNION ALL SELECT '<% run %>', 'w08', 'sentiment_' || OUTCOME || '_' || COALESCE(SENTIMENT, 'null'), COUNT(*), NULL
          FROM W08_SCORED GROUP BY OUTCOME, SENTIMENT;

SELECT FILE, OUTCOME, SENTIMENT, ROUND(CHAR_SIMILARITY, 3) SIM, LEFT(TRANSCRIPT, 160) TRANSCRIPT FROM W08_SCORED ORDER BY FILE LIMIT 4;
SELECT * FROM RESULTS WHERE RUN = '<% run %>' AND WORKLOAD = 'w08' ORDER BY METRIC;
